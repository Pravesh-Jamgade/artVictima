def parse_one_ipc_table(raw_str):
    """Parses the one_ipc text into a dict: {workload: {system: ipc_value}}"""
    lines = raw_str.strip().split('\n')
    header = lines[0].split()
    systems = header[1:] # e.g., ['perfect-tlb', 'perfect-pwc', ..., 'athena', ...]
    
    table_dict = {}
    for line in lines[1:]:
        parts = line.split()
        workload = parts[0]
        # Map each system name to its corresponding float value
        table_dict[workload] = dict(zip(systems, [float(x) for x in parts[1:]]))
    print(table_dict)
    return table_dict

def process(data_raw, dict_one_ipc):
    if not data_raw.strip():
        return
        
    for line in data_raw.strip().split('\n')[1:]:
        parts = line.split()
        if len(parts) < 3: continue
        
        mix_id = parts[0]
        sys_name = parts[1]
        core_ipcs = [float(val) for val in parts[2:]]
        
        workloads = workload_mixes[mix_id]

        # Verify system exists in baseline
        if sys_name not in dict_one_ipc[workloads[0]]:
            continue
        
        speedups = []
        for i, ipc in enumerate(core_ipcs):
            workload_name = workloads[i]
            baseline_ipc = dict_one_ipc[workload_name][sys_name]
            
            # Individual core speedup
            speedups.append(ipc / baseline_ipc)
        
        # 1. Weighted Speedup (Sum of speedups)
        weighted_sum = sum(speedups)
        
        # 2. Harmonic Speedup (N / Sum of reciprocals)
        # We use a small epsilon to avoid division by zero if an IPC is 0
        n_cores = len(speedups)
        harmonic_speedup = n_cores / sum(1.0 / s for s in speedups)
        
        print(f"{mix_id}, {sys_name}, {weighted_sum:.4f}, {harmonic_speedup:.4f}")

