f = io.StringIO(multicore_results.strip())
reader = csv.DictReader(f, delimiter='\t')

for row in reader:
    sota = row['sota']
    mix_name = row['mix']
    app_list = mixes[mix_name]
    
    weighted_ipc_sum = 0.0
    
    # Loop through each core (1 to 16)
    for i in range(1, 17):
        core_ipc_val = float(row[f'ipc{i}'])
        app_name = app_list[i-1]
        
        # Weighted IPC part = (Multicore IPC of app) / (Single core IPC of app)
        weighted_ipc_sum += (core_ipc_val / sc_ipc[app_name])
    
    print(f"{sota:<10} | {mix_name:<6} | {weighted_ipc_sum:<12.4f}")
